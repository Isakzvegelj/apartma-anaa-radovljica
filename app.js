function setHtml(selector, value) {
  const element = document.querySelector(selector);
  if (element) element.innerHTML = value;
}

function setTextList(selector, values) {
  document.querySelectorAll(selector).forEach((element, index) => {
    if (values[index] !== undefined) element.textContent = values[index];
  });
}

function setHtmlList(selector, values) {
  document.querySelectorAll(selector).forEach((element, index) => {
    if (values[index] !== undefined) element.innerHTML = values[index];
  });
}

function loadBentralWidget(widget, language) {
  widget.replaceChildren();
  const script = document.createElement('script');
  script.src = widget.dataset[`bentral${language === 'sl' ? 'Sl' : 'En'}`];
  widget.appendChild(script);
}

function setBentralLanguage(language) {
  document.querySelectorAll('[data-bentral-widget]').forEach((widget) => {
    loadBentralWidget(widget, language);
    const controls = document.querySelector(`[data-bentral-controls="${widget.dataset.bentralWidget}"]`);
    controls?.querySelectorAll('[data-bentral-language]').forEach((button) => {
      button.classList.toggle('is-active', button.dataset.bentralLanguage === language);
    });
  });
}

function applyLanguage(language) {
  const t = translations[language] || translations.en;
  document.documentElement.lang = language;
  document.title = t.title;
  document.querySelector('meta[name="description"]')?.setAttribute('content', t.description);
  setHtml('.brand strong', t.brand);
  setHtmlList('.desktop-nav a', t.nav);
  setTextList('.site-header > .button-small, .hero-actions .button-dark', [t.checkDates, t.heroCheck]);
  setHtml('.hero-copy > .eyebrow', `<span class="eyebrow-line"></span> ${t.heroEyebrow}`);
  setHtml('.hero h1', t.heroTitle);
  setTextList('.hero-intro', [t.heroIntro]);
  setHtml('.hero-actions .text-link', `${t.explore} <span>↓</span>`);
  setHtml('.hero-note span:last-child', t.rating);
  setHtml('.hero-stamp span', t.stamp);
  setTextList('.hero-caption span:nth-child(2)', [t.caption]);
  setHtml('.intro-grid > .eyebrow', `<span class="eyebrow-line"></span> ${t.introEyebrow}`);
  setHtml('.intro-grid h2', t.introTitle);
  setTextList('.intro-body p', [t.introBody]);
  setHtml('.intro-body .text-link', `${t.listing} <span>↗</span>`);
  setHtml('.stay-section .section-heading .eyebrow', `<span class="eyebrow-line"></span> ${t.stayEyebrow}`);
  setHtml('.stay-section .section-heading h2', t.stayTitle);
  setTextList('.stay-section .heading-aside', [t.stayAside]);
  setHtmlList('.feature-copy h3', t.features.map((feature) => feature[0]));
  setTextList('.feature-copy p', t.features.map((feature) => feature[1]));
  setTextList('.amenities span', t.amenities);
  setHtml('#availability .eyebrow', `<span class="eyebrow-line"></span> ${t.availabilityEyebrow}`);
  setHtml('#availability h2', t.availabilityTitle);
  setTextList('#availability .heading-aside', [t.availabilityAside]);
  setHtml('#pricing .eyebrow', `<span class="eyebrow-line"></span> ${t.ratesEyebrow}`);
  setHtml('#pricing h2', t.ratesTitle);
  setTextList('#pricing .heading-aside', [t.ratesAside]);
  setHtml('.location-copy .eyebrow', `<span class="eyebrow-line"></span> ${t.aroundEyebrow}`);
  setHtml('.location-copy h2', t.aroundTitle);
  setTextList('.location-copy > p:nth-of-type(2)', [t.aroundBody]);
  setHtml('.location-copy .button-outline', `${t.maps} <span>↗</span>`);
  document.querySelector('.map-card iframe')?.setAttribute('title', t.mapTitle);
  setTextList('.quote-section blockquote', [t.quote]);
  setTextList('.quote-section > p', [t.quoteSource]);
  setHtml('.booking-copy .eyebrow', `<span class="eyebrow-line"></span> ${t.bookingEyebrow}`);
  setHtml('.booking-copy h2', t.bookingTitle);
  setTextList('.booking-copy > p:not(.eyebrow)', [t.bookingBody]);
  setTextList('.booking-perks span', t.bookingPerks);
  setTextList('.official-links a', t.bookingLinks);
  setHtml('.brand-footer strong', t.brand);
  setHtml('.site-footer .footer-top > p', t.footerAddress);
  setTextList('.footer-bottom span:nth-child(2)', [t.footerPhoto]);
  setTextList('.footer-bottom a', [t.backTop]);
  const toggle = document.querySelector('#language-toggle');
  if (toggle) {
    toggle.textContent = t.languageButton;
    toggle.setAttribute('aria-label', t.languageAria);
  }
  document.querySelectorAll('[data-bentral-controls]').forEach((controls) => controls.setAttribute('aria-label', t.widgetLanguage));
  localStorage.setItem('anaa-language', language);
  setBentralLanguage(language);
}

const preferredLanguage = localStorage.getItem('anaa-language') || (navigator.language.toLowerCase().startsWith('sl') ? 'sl' : 'en');
applyLanguage(preferredLanguage);
document.querySelector('#language-toggle')?.addEventListener('click', () => {
  applyLanguage(document.documentElement.lang === 'sl' ? 'en' : 'sl');
});
